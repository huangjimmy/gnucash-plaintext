write_example "$B" 2026-12-31 \
    billed_in_us_and_hong_kong_dollars.txt \
    "A company billing in both US and Hong Kong dollars" \
    "Invoices in Canadian, US and Hong Kong dollars, with suppliers paid in" \
    "each. The Hong Kong dollar is pegged to the US dollar between 7.75 and" \
    "7.85, so its Canadian rate is the US rate over the peg — exact at each" \
    "end of the band with the US dollar at 1.30: 1/6 at 7.80, 26/155 at" \
    "7.75, 26/157 at 7.85. Those are the prices this book holds." \
    "" \
    "Each currency is measured against its own cost basis and no other. Draw" \
    "the same book as of 2026-11-30 and the peg is 7.85 instead, which turns" \
    "the Hong Kong figure negative while the US dollar stays where it was."

