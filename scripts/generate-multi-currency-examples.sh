    "4,000.00 dollars — and the rent paid in Canadian dollars throughout." \
    "" \
    "Nothing foreign is ever spent, so nothing is realized, and the holding" \
    "is measured against all four purchases together. The rent moves" \
    "total_assets every time and moves no gain at all."

# --- Bills in US and Hong Kong dollars --------------------------------------
