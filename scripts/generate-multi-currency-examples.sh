#!/usr/bin/env bash
# Write one example ledger per multi-currency scenario, with the statement it
# produces, into examples/multi-currency/.
#
# These are not test fixtures. Nothing asserts against them: they exist so a
# reader of docs/multi-currency.md can import one and get the same page the doc
# shows, rather than taking its word for it. They are generated from the
# fixtures in tests/fixtures/ and from what the tool actually prints, so
# regenerating them after a change is how they stay true.
#
#     ./scripts/generate-multi-currency-examples.sh            # in Docker
#     ./scripts/generate-multi-currency-examples.sh --here     # already inside
#
# Each file is the book exported whole — accounts, transactions and prices — so
# it re-imports into an empty book and draws the same statement with no rates
# file. That is the property that makes it checkable:
#
#     gnucash-plaintext import --new /tmp/check.gnucash <the example>
#     gnucash-plaintext balance-sheet /tmp/check.gnucash --as-of <the date>
#
# An export states `share_price:` as the value over the amount, which is the
# rate the two figures actually make. A ledger written by hand may state it to
# more places than the rounded value supports, and the import then says so and
# uses the amounts' — which is why these carry the export's form.
#
# **The `guid:` lines are load-bearing — do not strip them to tidy the files.**
# A disposal refers to the purchase it draws on by guid, in
# `cost_basis_split_guid:`. Remove the guids and that reference matches
# nothing, so the sale draws on no cost basis: measured on the buy-and-sell
# example, a guid-free copy imported at exit 0, said only
# `cost_basis_split_guid '...' matches no split in the book`, and drew a page
# reading 0.00 realized and 150.00 unrealized where the real book says 100.00
# and 0.00. Wrong, and quietly.
set -euo pipefail

TAG="${TAG:-latest}"
OUT="examples/multi-currency"
F="tests/fixtures"

if [ "${1:-}" != "--here" ]; then
    exec docker run --rm -v "$PWD:/workspace" --user "$(id -u):$(id -g)" \
        -e TAG="$TAG" -e REGENERATE="${REGENERATE:-}" "gnucash-dev:$TAG" bash -c \
        'set -e
         export HOME=/tmp/home PYTHONDONTWRITEBYTECODE=1
         mkdir -p $HOME
         cd /workspace
         python3 -m pip install -e ".[dev]" --break-system-packages --user -q 2>&1 | tail -1
         export PATH=$HOME/.local/bin:$PATH
         ./scripts/generate-multi-currency-examples.sh --here'
fi

BOOKS="$(mktemp -d)"
trap 'rm -rf "$BOOKS"' EXIT
mkdir -p "$OUT"

gp() { python3 -m cli.main "$@"; }

# GnuCash refuses a second save in the same second, so the backup a save would
# collide with is removed between steps, the way tests/conftest.py does it.
settle() { rm -f "$1".2* ; }

# The year-end price the reported example's rates file supplies, written into
# the book so the ledger prices itself and needs no --fx-rates.
year_end_price() {
    printf '%s\n' 'price' \
        '	commodity.namespace: "CURRENCY"' \
        '	commodity.mnemonic: "USD"' \
        '	currency.mnemonic: "CAD"' \
        '	time: "2026-12-31 12:00:00 +0000"' \
        '	value: "2773/2000"' \
        '	source: "user:price-editor"' \
        '	type: "last"' > "$BOOKS/year-end.txt"
}

# $1 book  $2 as-of  $3 file  $4 title  $5.. description lines
#
# Where the example already exists, its own ledger is what the book is rebuilt
# from, not the fixtures — so the guids stay as they were and a regeneration
# changes nothing unless a figure has. An export carries a guid for every
# account, transaction, split and price, and a fresh import mints new ones, so
# building from the fixtures every time rewrote every file on every run and
# no reader could tell a real change from the noise. Measured: importing an
# example as it stands and exporting it again writes the identical ledger.
#
# REGENERATE=fixtures rebuilds from tests/fixtures/ instead, which is what to
# use when a fixture or a figure has actually changed.
write_example() {
    local book="$1" as_of="$2" file="$3" title="$4"; shift 4
    local path="$OUT/$file"

    if [ -f "$path" ] && [ "${REGENERATE:-}" != fixtures ]; then
        sed '/^# ---------------------------------------------------------------$/,$d' \
            "$path" > "$BOOKS/existing.txt"
        local kept="$BOOKS/kept-$file.gnucash"
        rm -f "$kept" "$kept".2*
        if gp import --new "$kept" "$BOOKS/existing.txt" \
               --include-business-objects > /dev/null 2>&1; then
            rm -f "$kept".2*
            book="$kept"
        fi
    fi
    {
        echo "# $title"
        echo "#"
        for line in "$@"; do echo "# $line"; done
        echo "#"
        echo "# Generated by scripts/generate-multi-currency-examples.sh. Not a"
        echo "# test fixture — no test draws its figures from here — but the"
        echo "# statement below is checked against what the tool prints, by"
        echo "# tests/integration/test_each_worked_example_still_prints_the_statement_it_carries.py."
        echo "# Check it yourself:"
        echo "#"
        echo "#     gnucash-plaintext import --new /tmp/check.gnucash \\"
        echo "#         examples/multi-currency/$file"
        echo "#     gnucash-plaintext balance-sheet /tmp/check.gnucash --as-of $as_of"
        echo "#"
        echo "# The statement that ledger produces is at the end of this file."
        echo
    } > "$path"
    # Business objects as well as prices: the invoice scenarios are about a
    # customer being invoiced, and a file holding the posting transaction while
    # omitting the invoice and the customer is a poor example of that. It is
    # also what made those three churn — a ledger that states an `owner:` no
    # block in it declares does not re-import, so they were rebuilt from the
    # fixtures on every run and took fresh guids each time.
    gp export "$book" -o "$BOOKS/led.txt" \
        --include-prices --include-business-objects > /dev/null 2>&1
    cat "$BOOKS/led.txt" >> "$path"
    {
        echo
        echo "# ---------------------------------------------------------------"
        echo "# What \`balance-sheet --as-of $as_of\` prints for the book above."
        echo "#"
        echo "# Commented, every line of it. A statement opens with a dated"
        echo "# directive — \`$as_of balance-sheet\` — and the import reads a"
        echo "# line at column 0 as one, so a file carrying both would refuse to"
        echo "# import and this example would not do the one thing it is for."
        echo "# ---------------------------------------------------------------"
        echo
    } >> "$path"
    gp balance-sheet "$book" --as-of "$as_of" | sed 's/^/# /' >> "$path"

    # The file has to do what its own header tells a reader to do. A generator
    # that can write one which does not is worth no more than the claim it
    # makes, so this checks rather than trusts.
    local proof="$BOOKS/proof.gnucash"
    rm -f "$proof" "$proof".2*
    if ! gp import --new "$proof" "$path" > "$BOOKS/proof.log" 2>&1 \
       || grep -qi 'could not be read\|^Error' "$BOOKS/proof.log"; then
        echo "REFUSED: $path does not import — the example would be untrue" >&2
        sed -n '1,12p' "$BOOKS/proof.log" >&2
        exit 1
    fi
    echo "  wrote $path (imports clean)"
}

year_end_price

# --- A Canadian company invoices a US customer, and is later paid ------------
for state in held spent partly; do
    B="$BOOKS/$state.gnucash"
    gp import --new "$B" "$F/a_usd_invoice_collected_into_a_usd_bank.txt" \
        --fx-rates "$F/usd_at_the_invoice_rate_then_lower_at_the_year_end.yaml" \
        --include-business-objects > /dev/null
    settle "$B"
    if [ "$state" != held ]; then
        guid=$(gp fx-balances "$B" | grep 'Accounts Receivable USD' \
               | grep -oE '[0-9a-f]{32}' | head -1)
        src="$F/the_usd_bank_spent_out_against_its_basis.txt"
        [ "$state" = partly ] && src="$F/the_usd_bank_partly_spent_leaving_a_thousand.txt"
        sed "s/{usd_basis}/$guid/" "$src" > "$BOOKS/spend.txt"
        gp import "$B" "$BOOKS/spend.txt" \
            --fx-rates "$F/usd_at_the_invoice_rate_then_lower_at_the_year_end.yaml" > /dev/null
        settle "$B"
    fi
    gp import "$B" "$BOOKS/year-end.txt" > /dev/null
    settle "$B"
done

write_example "$BOOKS/held.gnucash" 2026-12-31 \
    a_us_customer_invoiced_and_the_dollars_still_held.txt \
    "A Canadian company invoices a US customer, and is later paid" \
    "2,720.00 USD billed and collected into a US dollar account. Every" \
    "transaction that brings the dollars in is stated in US dollars, so none" \
    "carries a Canadian figure and GnuCash's own reconstruction has nothing" \
    "to read. At the year end the company still holds all of them." \
    "" \
    "The dollars cost 3,791.14 and are worth 3,771.28, so 19.86 is" \
    "unrealized. Nothing is realized: no dollar has left."

write_example "$BOOKS/spent.gnucash" 2026-12-31 \
    a_us_supplier_paid_out_of_those_dollars.txt \
    "...and then pays a US supplier out of those dollars" \
    "The same company spends all 2,720.00 — a transfer to a payee and two" \
    "bank charges. Each disposal is valued at what those dollars cost, so" \
    "the splits facing it state what they fetched and \$residual\$ takes the" \
    "difference." \
    "" \
    "The 19.86 has moved from unrealized to realized, and nothing is" \
    "unrealized because nothing is held."

write_example "$BOOKS/partly.gnucash" 2026-12-31 \
    some_of_the_dollars_kept_back.txt \
    "...and keeps some of the money back" \
    "The same again, except 1,000.00 USD stays in the account. Both kinds of" \
    "gain are on the page at once: 12.56 realized on what left, 7.30" \
    "unrealized on what is still held." \
    "" \
    "Drawn at another price the realized figure does not move and the" \
    "unrealized one does, which is why they cannot share a line."

# --- Paid several times, several bills paid ---------------------------------
B="$BOOKS/several.gnucash"
gp import --new "$B" "$F/a_cad_book_earning_usd_three_times.txt" > /dev/null
settle "$B"
a=$(gp fx-balances "$B" | grep '^2026-02-01' | grep -oE '[0-9a-f]{32}' | head -1)
b=$(gp fx-balances "$B" | grep '^2026-04-01' | grep -oE '[0-9a-f]{32}' | head -1)
c=$(gp fx-balances "$B" | grep '^2026-06-01' | grep -oE '[0-9a-f]{32}' | head -1)
sed -e "s/{basis_at_130}/$a/g" -e "s/{basis_at_135}/$b/g" -e "s/{basis_at_140}/$c/g" \
    "$F/the_usd_earned_three_times_spent_out_in_four.txt" > "$BOOKS/four.txt"
gp import "$B" "$BOOKS/four.txt" > /dev/null
settle "$B"
write_example "$B" 2026-12-31 \
    paid_in_dollars_three_times_and_three_bills_paid.txt \
    "A company paid in US dollars several times, paying several US bills" \
    "Consulting collected three times — 1,000.00 USD at 1.30, 2,000.00 at" \
    "1.35, 1,000.00 at 1.40 — and four subcontractors paid out of it at" \
    "1.45, 1.50, 1.38 and 1.42." \
    "" \
    "Three cost bases, four disposals, and the first basis is emptied by the" \
    "second payment made against it — so the realized figure has to add up" \
    "across both. It comes to 250.00, and the working lists all four."

# --- Holds US dollars, pays its own bills at home ---------------------------
B="$BOOKS/athome.gnucash"
gp import --new "$B" \
    "$F/a_cad_book_that_bought_usd_at_four_rates_and_spends_only_cad.txt" > /dev/null
